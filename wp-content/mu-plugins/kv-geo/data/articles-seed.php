function kv_seed_import_articles() {
  $articles = kv_seed_articles();
  $created = [];

  foreach ($articles as $a) {
    // Skip if post with this slug exists
    $existing = get_page_by_path($a['slug'], OBJECT, 'post');
    if ($existing) {
      $created[] = ['slug' => $a['slug'], 'status' => 'exists', 'id' => $existing->ID];
      continue;
    }

    // Create/get category
    $catId = 0;
    if (!empty($a['category'])) {
      $cat = get_term_by('name', $a['category'], 'category');
      if ($cat) {
        $catId = $cat->term_id;
      } else {
        $newCat = wp_insert_term($a['category'], 'category');
        if (!is_wp_error($newCat)) {
          $catId = $newCat['term_id'];
        }
      }
    }

    $postId = wp_insert_post([
      'post_title'   => $a['title'],
      'post_name'    => $a['slug'],
      'post_content' => $a['content'],
      'post_excerpt' => $a['excerpt'] ?? '',
      'post_status'  => 'draft',
      'post_type'    => 'post',
      'post_category' => $catId ? [$catId] : [],
    ], true);

    if (is_wp_error($postId)) {
      $created[] = ['slug' => $a['slug'], 'status' => 'error', 'error' => $postId->get_error_message()];
      continue;
    }

    // Add tags
    if (!empty($a['tags']) && is_array($a['tags'])) {
      wp_set_post_tags($postId, $a['tags'], false);
    }

    $created[] = ['slug' => $a['slug'], 'status' => 'created', 'id' => $postId];
  }

  return $created;
}

